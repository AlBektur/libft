#include "libft.h"

char	*ft_strdup(const char *s)
{
	int		i;
	char	*res;
	int		len;

	len = ft_strlen(s);
	res = malloc(sizeof(char) * len + 1);
	if (!res)
		return (NULL);
	i = 0;
	while (i < len)
	{
		res[i] = s[i];
		i++;
	}
	res[i] = '\0';
	return (res);
}
